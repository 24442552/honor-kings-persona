def finish_spec(name: str, title: str, role: str, lanes: list[str], spec: dict[str, str]) -> dict[str, str]:
    lane = lanes[0]
    pair = NICKS.get(name)
    nick_bad = spec.get("nick_bad") or (pair[0] if pair else None) or LANE_NICK_BAD.get(lane, "路人印象")
    nick_good = spec.get("nick_good") or (pair[1] if pair else None) or ROLE_NICK_GOOD.get(role, title)
    out = dict(spec)
    out["epithet"] = f"{nick_bad}的{nick_good}的{name}"
    return out


