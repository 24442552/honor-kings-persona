def build_heroes() -> list[dict]:
    raw = json.loads((ROOT / "herolist.json").read_text(encoding="utf-8"))
    specs = specials()
    heroes = []
    for item in raw:
        name = item["cname"]
        title = item.get("title") or "无名"
        hid = item["ename"]
        role = role_of(item.get("hero_type") or 1, name)
        lanes = lane_of(item.get("roles") or "", item.get("extra_cold_lane") or "")
        spec = specs.get(name) or template_spec(name, title, role, lanes)
        spec = finish_spec(name, title, role, lanes, spec)
        vec = base_vec(role, lanes)
        apply_nudge(vec, name, specs.get(name) or {})
        heroes.append({
            "id": hid,
            "name": name,
            "title": title,
            "role": role,
            "lanes": lanes,
            "img": f"https://game.gtimg.cn/images/yxzj/img201606/heroimg/{hid}/{hid}.jpg",
            "vec": {k: round(float(val), 2) for k, val in vec.items()},
            **spec,
            "laneGood": LANE_TRAIT[lanes[0]]["good"],
            "laneBad": LANE_TRAIT[lanes[0]]["bad"],
            "laneMeta": LANE_TRAIT[lanes[0]]["meta"],
            "roleGood": ROLE_TRAIT[role]["good"],
            "roleBad": ROLE_TRAIT[role]["bad"],
            "roleMeta": ROLE_TRAIT[role]["meta"],
        })
    return heroes


