def lane_of(roles: str, extra: str) -> list[str]:
    ids = []
    for chunk in (roles or "").split("|"):
        chunk = chunk.strip()
        if chunk.isdigit():
            ids.append(int(chunk))
    for chunk in (extra or "").split("|"):
        chunk = chunk.strip()
        if chunk.isdigit():
            ids.append(int(chunk))
    names = []
    for i in ids:
        n = LANE_NAME.get(i)
        if n and n not in names:
            names.append(n)
    return names or ["游走"]


